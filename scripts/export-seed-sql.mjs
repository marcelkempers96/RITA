// Writes supabase/seed.sql: every entry in src/content/** as a row of public.content.
// Re-running the seed updates existing rows (matched on collection + slug) and keeps owners.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src', 'content');
const rows = [];
for (const collection of readdirSync(dir)) {
  for (const file of readdirSync(join(dir, collection)).filter((f) => f.endsWith('.json'))) {
    const data = JSON.parse(readFileSync(join(dir, collection, file), 'utf8'));
    const status = data.status === 'draft' ? 'draft' : 'published';
    delete data.status;
    const json = JSON.stringify(data);
    if (json.includes('$rita$')) throw new Error(`unexpected delimiter in ${collection}/${file}`);
    rows.push(`('${collection}', '${file.slice(0, -5).replace(/'/g, "''")}', $rita$${json}$rita$::jsonb, '${status}')`);
  }
}
const sql = `-- Generated by scripts/export-seed-sql.mjs from src/content. Run after schema.sql.
-- ${rows.length} rows. Existing rows are updated; owners are kept.
insert into public.content (collection, slug, data, status) values
${rows.join(',\n')}
on conflict (collection, slug) do update set data = excluded.data, status = excluded.status;
`;
writeFileSync(join(root, 'supabase', 'seed.sql'), sql);
console.log(`seed.sql: ${rows.length} rows`);
